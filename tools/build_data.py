"""Regenerate data.js from the files in data/.

Usage (from the repo root):  python tools/build_data.py
Edit or replace a CSV/JSON in data/, add or change its entry in data/datasets.json,
run this script, then commit and push. GitHub Pages republishes in about a minute.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = json.load(open(os.path.join(ROOT, 'data', 'datasets.json'), encoding='utf-8'))
payload = {}
for did, m in cfg['datasets'].items():
    path = os.path.join(ROOT, m['file'])
    payload[did] = {'format': 'json' if path.endswith('.json') else 'csv', 'text': open(path, encoding='utf-8').read()}
with open(os.path.join(ROOT, 'data.js'), 'w', encoding='utf-8') as fh:
    fh.write('// Generated by tools/build_data.py from the files in data/. Edit those, then rerun.\n')
    fh.write('window.DASH_DATA = ' + json.dumps(payload) + ';\n')
    fh.write('window.DASH_META = ' + json.dumps(cfg['datasets'], indent=1) + ';\n')
    fh.write('window.DASH_PARAMS = ' + json.dumps(cfg['params']) + ';\n')
print('Wrote data.js with', len(payload), 'datasets')
